import puppeteer from 'puppeteer-core';
const b = await puppeteer.launch({ executablePath: '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome', headless: true, userDataDir: '/private/tmp/claude-501/alda-live-check', args: ['--hide-scrollbars'] });
const p = await b.newPage();
await p.setViewport({ width: 1440, height: 900, deviceScaleFactor: 1 });
const errs = [], fails = [];
p.on('pageerror', (e) => errs.push(String(e)));
p.on('requestfailed', (r) => fails.push(r.url()));
p.on('response', (r) => { if (r.status() >= 400) fails.push(r.status() + ' ' + r.url()); });
const t0 = Date.now();
await p.goto('https://sindrimar02.github.io/aldamusic-preview/?c=' + Date.now(), { waitUntil: 'load' });
await p.waitForFunction(() => !document.body.classList.contains('al-loading') && !document.body.classList.contains('al-intro'), { timeout: 20000 });
const ready = Date.now() - t0;
await p.evaluate(() => { const s = document.querySelector('#plotur'); scrollTo(0, scrollY + s.getBoundingClientRect().top + 250); });
await new Promise((r) => setTimeout(r, 1500));
const pt = await p.evaluate(() => { const a = [...document.querySelectorAll('.al-rel')].find((e) => { const r = e.getBoundingClientRect(); return r.left > 300 && r.right < innerWidth - 500 && r.top > 0 && r.bottom < innerHeight; }); const r = a.getBoundingClientRect(); return { x: r.left + r.width / 2, y: r.top + r.width / 2 }; });
await p.mouse.move(pt.x, pt.y);
await new Promise((r) => setTimeout(r, 1300));
const hov = await p.evaluate(() => { const c = document.querySelector('.al-rel[data-out]'); if (!c) return 'no hot card'; const d = c.querySelector('.al-rel-disc'); const fr = c.querySelector('.al-rel-frame').getBoundingClientRect(); const r = d.getBoundingClientRect(); return { disc: getComputedStyle(d).display, tf: getComputedStyle(d).transform, peek: Math.round(r.right - fr.right) }; });
await p.screenshot({ path: '/private/tmp/claude-501/alda-live-hover.png', clip: { x: 0, y: 100, width: 1440, height: 500 } });
await p.mouse.move(20, 20);
await new Promise((r) => setTimeout(r, 1400));
const after = await p.evaluate(() => ({ hot: document.querySelectorAll('[data-disc]').length, out: document.querySelectorAll('[data-out]').length }));
console.log(JSON.stringify({ readyMs: ready, hov, after, errs, fails: fails.slice(0, 5) }));
await b.close();
